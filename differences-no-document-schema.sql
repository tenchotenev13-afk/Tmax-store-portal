-- differences_reports в sync-mirror.ps1. Иначе огледалото ще тегли
-- таблицата без нея.

-- ─── ROLLBACK ────────────────────────────────────────────────────────────
-- Обратима без загуба на друго: колоната е нова и никой заварен ред не
-- зависи от нея. Клиентът чете rep.no_document като falsy, ако колоната
-- липсва — баджът и текстът „няма (стока без документ)" просто не излизат.
-- Ако вече има бланки, подадени с отметката, информацията за тях се губи.
--
--   alter table differences_reports drop column if exists no_document;
