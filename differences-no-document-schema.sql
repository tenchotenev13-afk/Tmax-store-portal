-- differences-no-document-schema.sql
-- Отметка „Без документ" върху public.differences_reports.
-- Приложено в Supabase (xiwkdiqqplgdcrkewgtv) на 12.09.2026,
-- миграция differences_reports_no_document (версия 20260912213248).
--
-- ЗАЩО
-- Магазините понякога получават стока без документ — тогава няма какво да
-- снимат, а формата за нова бланка спираше подаването заради задължителните
-- снимки при категориите „Увредена стока" и „Грешен баркод". Отметката
-- отменя ЕДИНСТВЕНО снимките: наименованието на артикула остава
-- задължително, SAP кодът и досега не е.
--
-- Има смисъл само при посока „Доставчик". При междускладов трансфер и при
-- сторна по грешен прием документ винаги има — там отметката не се рисува
-- и стойността остава false.
--
-- ЗАЩО NOT NULL DEFAULT FALSE, А НЕ NULLABLE
-- Клиентът пише винаги булева стойност (false при изключена отметка, не
-- липсващ ключ). Нулевата стойност би означавала „не знам", а такъв случай
-- няма: всяка бланка или е без документ, или не е. Default false покрива и
-- всичките заварени бланки — към 12.09.2026 те са 133, всичките false.
--
-- ГРАНТ НЕ Е НУЖЕН
-- differences_reports има ТАБЛИЧЕН грант за anon
-- (relacl = anon=arwdDxtm/postgres), тоест новата колона се покрива
-- автоматично. Верният източник за тази проверка е pg_class.relacl, не
-- information_schema.column_privileges — то разгъва табличния грант по
-- колони и показва редове, каквито няма.

alter table differences_reports
  add column if not exists no_document boolean not null default false;

comment on column differences_reports.no_document is
  'Магазинът е отбелязал, че стоката е дошла без документ — снимки не са задължителни';

-- ЗА ЖИВКО (огледалото)
