-- Обикновена задача със СРОК В ПО-КЪСНА СЕДМИЦА: bulletin_tasks.spans_from
--
-- До 25.09.2026 обикновената задача живееше точно в един бюлетин: клиентът,
-- отчетите и известията я четат с `bulletin_id=eq.<бюлетина на седмицата>`.
-- Задача, поставена на 1.10 (С40) със срок 8.10 (С41), значеше или две
-- отделни задачи (две отмятания, две X/18, два отчета), или задача, която в
-- С41 изчезва от екрана, макар срокът ѝ да е точно там.
--
-- Задачата остава ЕДИН ред. Новото е откъде НАЧАЛО се вижда:
--   spans_from = понеделникът на седмицата, в която е поставена (W).
--   NULL       = обикновена задача, точно както досега.
--
-- ═══ ДВЕТЕ ПРАВИЛА ══════════════════════════════════════════════════════
-- За седмица V (понеделник V.mon, неделя V.sun):
--   ВИЖДА СЕ    ⟺ bulletin_id = бюлетина на V   (както винаги)
--                 ИЛИ  spans_from <= V.sun  И  due_date >= V.mon
--   БРОИ СЕ     ⟺ due_date е в V
-- Второто важи и за обикновените задачи (срокът им е в тяхната седмица),
-- затова правилото не ги пипа. За многоседмичната то значи: показва се от W
-- до седмицата на срока, но в числителя и знаменателя влиза само в
-- седмицата на срока — дотогава е „в срок", не „неизпълнена".
-- Виж taskSpansWeeks() / taskCountsInWeek() / loadSpanningTasks() в shared.js.
--
-- ═══ ЗАЩО ИЗРИЧНА КОЛОНА, А НЕ СМЕТКА ПО ДАТИТЕ ═════════════════════════
-- Условието „срокът е извън седмицата на бюлетина" изглежда достатъчно, но:
--   · В базата ВЕЧЕ има три такива задачи — „Провери наличности", „Грешно
--     нетно съдържание", „Задължителна преоценка", всичките С29/2026
--     (понеделник 13.07) с due_date = 12.07, тоест ден ПРЕДИ седмицата си.
--     Изведено правило ги обявява за многоседмични. С колоната (NULL при тях)
--     остават инертни завинаги.
--   · Филтър само по дати тече НАЗАД: „срок >= понеделника на показаната
--     седмица" хваща и задачите на БЪДЕЩ бюлетин, тоест задача от С41 щеше
--     да се появи в С40, преди да е поставена. Нужно е „поставена е до тази
--     седмица" — това е spans_from <= V.sun.
--   · Условието се пише на четири места (клиент + 3 едж функции). С две дати
--     е един and(...); с week_number/year е сметка за ISO седмици при Нова
--     година в четири диалекта.
--
-- ═══ ОГРАНИЧЕНИЯТА ══════════════════════════════════════════════════════
-- Всичките важат САМО при spans_from IS NOT NULL, тоест нищо от заварените
-- 30 задачи със срок не се докосва:
--   · due_date is not null      — без срок няма какво да се пренася;
--   · cardinality(due_dates)<=1 — срокът е ЕДИН ден (решението на Тенчо,
--     25.09.2026). Многодневната задача се отмята по ден и би значела
--     няколко отмятания, тоест точно обратното на „една отчетност";
--   · due_date >= spans_from+7  — срокът е в ПО-КЪСНА седмица; иначе
--     задачата е обикновена и spans_from само обърква четящия;
--   · due_date <= spans_from+27 — горна граница ЧЕТИРИ седмици (W + 3).
--     По-далеч е планиране, не задача в бюлетин.
-- spans_from е понеделник — extract(isodow) = 1, като границите на
-- периодите и версиите на постоянните задачи.
--
-- ═══ КАКВО НЕ СЕ ПРОМЕНЯ ════════════════════════════════════════════════
-- · task_completions: един ред на обект, completion_date = СРОКЪТ. Оттам
--   идват „едно X/18" и „една отчетност". Частичните уникални индекси от
--   20260910231103 продължават да пазят дубликатите.
-- · transit_sync_completions(): филтрира по linked_module/auto_complete и
--   `coalesce(due_dates[1],due_date) >= днес-14`, БЕЗ филтър по седмица или
--   бюлетин, и пише completion_date = срокът. Бъдещ срок минава границата,
--   значи автоматичното отмятане на „Стока на път" работи непроменено.
-- · Публикуването: видимостта следва бюлетина, в който задачата е
--   ПОСТАВЕНА (W). Чернова W значи скрита и в по-късните седмици; статусът
--   на по-късния бюлетин е без значение.
--
-- Rollback: supabase/migrations/20260925141230_bulletin_task_spans_from_down.sql

alter table public.bulletin_tasks
  add column if not exists spans_from date;

alter table public.bulletin_tasks
  add constraint bulletin_tasks_spans_from_mon_chk
    check (spans_from is null or extract(isodow from spans_from) = 1),
  add constraint bulletin_tasks_spans_due_req_chk
    check (spans_from is null or due_date is not null),
  add constraint bulletin_tasks_spans_single_day_chk
    check (spans_from is null or coalesce(cardinality(due_dates), 0) <= 1),
  add constraint bulletin_tasks_spans_later_week_chk
    check (spans_from is null or due_date >= spans_from + 7),
  add constraint bulletin_tasks_spans_max_weeks_chk
    check (spans_from is null or due_date <= spans_from + 27);

create index if not exists bt_spans_from_due_idx
  on public.bulletin_tasks (spans_from, due_date)
  where spans_from is not null;

comment on column public.bulletin_tasks.spans_from is
  'Понеделникът на седмицата, в която задачата е поставена — от него задачата се вижда във всяка седмица до тази на due_date включително. NULL = обикновена задача (живее само в своя бюлетин). Брои се САМО в седмицата на due_date.';
comment on index public.bt_spans_from_due_idx is
  'Заявката за многоседмични задачи на показаната седмица: spans_from <= неделя AND due_date >= понеделник.';
