-- Документ при отмятане на задача
-- Приложено: 26.08.2026 · миграция task_completions_files
--
-- Досега видовете задача бяха четири и нито един не искаше документ:
-- info (само отметка), photo, comment, photo_comment. При задача като
-- „Ревизии 953" магазинът пишеше коментар „качено в САП", а самият файл
-- не влизаше в портала.
--
-- Това вече се случваше, но по грешния път: полето за снимка има
-- accept=".jpg,.jpeg,.png,.gif,.webp", а accept е подсказка към диалога за
-- избор, НЕ проверка. Към 26.08.2026 в колоната photos лежат три записа с
-- .xlsx (Шумен веднъж, Раднево два пъти) и един .png със снимка на същото.
-- Следствието се вижда: report.js и today.js рендират всеки запис от photos
-- като <img src>, тоест таблиците излизат като счупени картинки в дневния
-- имейл и в таб „Днес".
--
-- files е отделна колона нарочно, не разширение на photos: двете се
-- показват различно (миниатюра срещу връзка с име на файла) и се искат от
-- различни видове задача. Формата е същата — масив от {url, filename}.
--
-- Старите записи НЕ се пипат. Трите .xlsx остават в photos; вместо
-- миграция на данни, рендирането на photos проверява разширението и
-- показва неснимков файл като връзка. Това е и защитата, ако някой пак
-- качи документ през полето за снимка.
--
-- Грант НЕ е нужен: task_completions има ТАБЛИЧЕН грант за anon
-- (relacl = anon=arwdDxtm/postgres), тоест новата колона се покрива
-- автоматично. За сравнение users има само anon=d/postgres и затова там
-- всяка колона иска изричен grant.
-- ⚠️ information_schema.column_privileges НЕ става за тази проверка — то
-- разгъва табличния грант по колони и показва редове, каквито няма.
-- Верният източник е pg_class.relacl.

alter table public.task_completions
  add column if not exists files jsonb null;

comment on column public.task_completions.files is
  'Документи, приложени при отмятане: [{url, filename}]. Отделно от photos — показва се като връзка с име на файла, не като миниатюра.';

