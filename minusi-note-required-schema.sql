-- ЗАЩО. Проверка в базата на 22.10.2026: Гоце Делчев попълни 98275 (955 от
-- 07.10, док. 4903341685/1) и 32033 (955 от 11.10, док. 4903347366/1) с
-- причина „клиентска поръчка (номер/дата)" (id 1), но с празна бележка —
