-- Постоянна задача с ПРОЗОРЕЦ за изпълнение
-- Приложено: 24.08.2026 · миграция recurring_tasks_due_window
--
-- Днес всяко явяване на постоянна задача е отделно задължение: due_weekdays
-- = [0,1,2] значи ТРИ чекбокса в календара, три отмятания и три единици в
-- знаменателя на статистиката. За „подаване на справка до сряда" това е
-- грешно — свършена в понеделник е свършена.
--
-- due_window = true превключва смисъла на due_weekdays:
--   · последният ден от списъка е СРОКЪТ
--   · предходните дни са „разрешено по-рано"
--   · една отметка където и да е в прозореца затваря задачата за цялата
--     седмица — ЕДИН елемент в статистиката, не N
--
-- Полето има смисъл само при 2..6 избрани дни. При 0 или 1 няма какво да е
-- „по-рано"; при всичките 7 задачата е „всеки ден" (така е зададен „Вечерен
-- оборот") и прозорец през цялата седмица би значел просто „когато и да е".
-- Извън този диапазон стойността се ИГНОРИРА от клиента, а превключвателят
-- в интерфейса е недостъпен — не се променя поведение мълчаливо.
--
-- default false: към 24.08.2026 активните постоянни задачи са 12, от които
-- една многодневна („Вечерен оборот", due_weekdays=[0..6] = всеки ден).
-- Нито една не се променя от тази миграция.

alter table public.recurring_tasks
  add column if not exists due_window boolean not null default false;

comment on column public.recurring_tasks.due_window is
  'true = due_weekdays е прозорец (последният ден е срок, една отметка затваря седмицата), не N отделни задължения. Игнорира се при по-малко от 2 или повече от 6 избрани дни.';

