-- Жокер по обект към постоянна задача: recurring_tasks.store_hints
--
-- ═══ ЗАЩО ═══════════════════════════════════════════════════════════════
-- „ЗАРЕЖДАНЕ КОЛОРАНТИ" (понеделник 11:00) е една задача за всички обекти,
-- но всеки обект поръчва РАЗЛИЧЕН набор колоранти (Петрич: COLTEC + WB,
-- Шумен: COLTEC + KRAFT, Севлиево/Козлодуй: само NT GBC и т.н.). Колегите
-- пратиха списъка по обект (колоранти.xlsx, 13 листа, 11.10.2026). Обектът
-- трябва да го вижда ПОД задачата, като подсказка при набирането в SAP —
-- не да го търси в общия прикачен файл.
--
-- ═══ КАКВО ══════════════════════════════════════════════════════════════
-- Една jsonb колона: { "<store_name>": "<текст>", … }. Ключът е ТОЧНО
-- users.store_name / stores.name („Гоце Делчев", не „гоце делчев"). Текстът е
-- свободен (pre-line), редактира се от Бюлетина с бутона „💡 Жокери по обект"
-- на реда на постоянната задача (canEdit), PATCH върху recurring_tasks.
-- Обект без ключ не вижда нищо. Глобалните роли виждат всички обекти.
--
-- НЕ е част от RECURRING_CONTENT_FIELDS (shared.js), тоест НЕ се версионира
-- по седмици — както attachments и sort_order (решение 24.09.2026):
-- списъкът на обекта е общ за всички седмици. recurringApplyVersion() копира
-- всички ключове на реда, така че store_hints стига до слятата задача без
-- промяна там.
--
-- ═══ ЗАВАРЕНИТЕ ДАННИ (правило 9) ═══════════════════════════════════════
-- Нова колона с NULL — 0 засегнати реда. Seed-ът за колорантите е отделно:
-- recurring-task-store-hints-data.sql (само данни).
--
-- RLS: recurring_tasks е С включено RLS, но политиките за anon са
-- permissive („Allow update recurring_tasks" — using (true), без колонни
-- ограничения; проверено 11.10.2026 в pg_policies). attachments се пишат по
-- същия път. Нищо ново за компромиса.
--
-- ROLLBACK (губи всички жокери — без резервно копие):
--   alter table public.recurring_tasks drop column if exists store_hints;
--
-- Огледало (Живко): една нова колона → zhivko-opashka.md.

alter table public.recurring_tasks
  add column if not exists store_hints jsonb;

comment on column public.recurring_tasks.store_hints is
  'Жокер по обект: {"<store_name>": "<текст>"}. Общ за всички седмици (не се версионира). Редактира се от Бюлетина.';
