-- КАКВО БЕШЕ
-- Политиката app_settings_public_report_keys пускаше на anon ТРИ ключа:
--   returns_stale_days, kasa_diff_threshold, storno_small_sum
-- Третият НЕ СЪЩЕСТВУВА. Истинското име е storno_small_threshold, тоест
-- политиката пазеше ключ-призрак, а истинският ключ беше блокиран.
--
-- КАКВО РЕАЛНО ЧЕТЕ БРАУЗЪРЪТ (сверено по кода на 28.09.2026 — осем ключа)
--   kasa_diff_threshold       report.js:344   и report.js:1715   ✓ пускан
--   returns_stale_days        report.js:1706                     ✓ пускан
--   storno_small_threshold    report.js:1716                     ✗ блокиран
--   diff_stale_days           report.js:1736                     ✗ блокиран
--   pallets_drop_threshold    pallets.js:370                     ✗ блокиран
--   report_excluded_stores    shared.js:311                      ✗ блокиран
--   loading_transit_docs      loading.js:2534 (LL_FEATURE_KEYS)  ✗ блокиран
--   loading_scan              loading.js:2534 (LL_FEATURE_KEYS)  ✗ блокиран
-- Таблицата държи десет реда. Другите два (daily_report_managers,
-- weekly_report_managers) не се искат от браузъра, но от 28.09.2026 СА четими с
-- публичния ключ — политиката е `using (true)`, без изключения. Това е
-- приемливо заради СЪДЪРЖАНИЕТО им, не защото са скрити: и двата са
-- превключвател със стойност 'on' (сверено 28.09.2026), а не списък с хора,
-- както подсказва името „managers". Че кодът не ги чете, е отделен факт и НЕ е
-- защита — утре някой може да ги зачете, без да пипа политиката.
--
-- ЗАЩО НЯМАШЕ ВИДИМА ЩЕТА
-- Шестте блокирани заявки не гърмят — PostgREST връща ПРАЗЕН резултат, не
-- грешка, и кодът пада на резервната си стойност. Днес резервите СЪВПАДАТ с
-- базата: storno_small_threshold е 5 и резервата е 5; двата превключвателя са
-- 'off' и резервата е изключено; списъкът с изключени обекти съвпада с твърдия
-- масив в shared.js. Тоест дефектът беше спящ и чакаше първата промяна от
-- Администрация, за да се събуди: кронът (service ключ, минава над RLS) щеше да
-- усвои новата стойност, а браузърът не — и никой нямаше да разбере защо.
--
-- Точно това правеше report_excluded_stores безсмислен от деня, в който беше
-- въведен (28.09.2026): ключът съществува, за да има ЕДИН източник вместо два, а
-- политиката го връщаше на два — база за крона, твърд масив за браузъра.
--
-- ЗАЩО НЕ ПОПРАВИХМЕ СПИСЪКА, А ГО МАХНАХМЕ
-- Списъкът вече остаря ДВА пъти независимо: веднъж по име (storno_small_sum) и
-- веднъж по обхват (таблицата порасна, кодът зачете нови ключове). Поправен
-- списък щеше да остарее трети път при следващия ключ, и пак тихо. Затова
-- политиката вече не изброява: `using (true)` за SELECT.
--
-- КАКВО ЗНАЧИ ТОВА ЗА СЪДЪРЖАНИЕТО — ПРАВИЛО
-- Проверени са всичките десет реда към 28.09.2026: прагове в дни и бройки,
-- списък с имена на обекти, два превключвателя on/off, два списъка с имейли на
-- управители. Нищо чувствително. От тук нататък в app_settings НЕ влиза
-- стойност, която не бива да се чете с публичния ключ. Дотрябва ли такава,
-- мястото ѝ е отделна таблица или едж функция със service ключ (образецът е
-- auth-login), НЕ нов ред тук. Записано е и в CLAUDE.md, при RLS.
--
-- ПИСАНЕТО ОСТАВА ЗАТВОРЕНО
-- Няма и не се добавя политика за INSERT/UPDATE/DELETE за anon. Стойностите се
-- менят само със service ключ — от Администрация през едж функция или ръчно.
--
-- ОГЛЕДАЛО (Живко): само политика, без таблици и колони — за огледалото нищо не
-- се мени. Тегленето е с anon ключа, тоест то ПЕЧЕЛИ от промяната: дотук
-- app_settings му се е връщала с два реда вместо с десет.
--
-- ЖИВО СЪСТОЯНИЕ към 28.09.2026 (сверено с pg_policy):
--   RLS: включено
--   app_settings_anon_select_all · SELECT · {anon} · using (true) · без with_check
--   друга политика по тази таблица НЯМА

drop policy if exists app_settings_public_report_keys on public.app_settings;

create policy app_settings_anon_select_all on public.app_settings
  for select to anon
  using (true);
