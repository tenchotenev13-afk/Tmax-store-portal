-- weekly-checklist-sends-schema.sql
-- Дневник на изпращанията на седмичния чек лист.
-- НЕ Е ПРИЛОЖЕНО. Прилага се ръчно след преглед.
--
-- ЗАЩО ОТДЕЛНА ТАБЛИЦА, А НЕ ПОЛЕ „изпратено" В weekly_checklist
-- Една седмица може да се прати НЯКОЛКО пъти: контролингът изпраща, после
-- обектът възразява, поправя се клетка и се праща пак. Тоест състоянието
-- принадлежи на ИЗПРАЩАНЕТО, не на реда с отметката.
--
-- Булево поле в weekly_checklist би могло да пази само последното „да" и
-- заедно с това би отговорило грешно на всеки въпрос, който има значение:
-- кога е тръгнало, кой го е пратил, коя поред е версията и какво е било
-- поправено между двете. А и weekly_checklist има ред на КЛЕТКА (обект ×
-- показател), тоест флагът щеше да се повтори 100+ пъти за една седмица и
-- да позволи половин седмица да е „изпратена", а другата половина не.
--
-- ЗАЩО СЕ ПАЗИ СПИСЪКЪТ ПОЛУЧАТЕЛИ
-- Съставът на обектите и на хората се мени: обект се закрива, регионален
-- сменя района си, някой напуска. Изведе ли се списъкът наново при въпрос
-- „кой получи версия 1", отговорът ще е ДНЕШНИЯТ състав, не тогавашният —
-- тихо неверен и невъзможен за оспорване. Затова адресите се записват
-- такива, каквито са били в момента на изпращането.
-- Това е и причината колоната да е text[], а не връзка към users: записът
-- трябва да преживее изтрит потребител.

create table if not exists public.weekly_checklist_sends (
  id          uuid primary key default gen_random_uuid(),
  year        int  not null,
  week_number int  not null,
  -- Поредният номер на изпращането ЗА ТАЗИ СЕДМИЦА: 1, 2, 3 …
  -- Смята се от КЛИЕНТА (чете последната за седмицата и добавя едно).
  -- Тригер тук би бил излишна сложност: една седмица се праща веднъж-два
  -- пъти, не хиляди, и няма конкуренция, срещу която да се пази.
  -- Уникалността по-долу пази от дублиран номер, ако все пак двама натиснат
  -- едновременно — тогава вторият получава грешка и опитва пак.
  version     int  not null,
  sent_at     timestamptz not null default now(),
  -- display_name на изпращача, не id: записът е за четене от човек и трябва
  -- да остане четим, ако профилът бъде изтрит.
  sent_by     text not null,
  -- Адресите, на които реално е тръгнало. Виж бележката горе.
  recipients  text[] not null,
  -- По избор: какво е поправено спрямо предишната версия.
  note        text,
  created_at  timestamptz not null default now(),

  constraint weekly_checklist_sends_uniq
    unique (year, week_number, version),
  constraint weekly_checklist_sends_week_chk
    check (week_number between 1 and 53),
  constraint weekly_checklist_sends_version_chk
    check (version >= 1),
  -- Изпращане до НУЛА адреса не е изпращане, а неуспял опит: писмо не е
  -- тръгнало до никого. Записан без това ограничение, редът щеше да изглежда
  -- като успешно изпращане — с час, с автор и с пореден номер — и да заеме
  -- version, който после липсва. Празен масив не е „още не знаем кой": за
  -- това състояние просто няма ред.
  --
  -- ⚠️ cardinality, А НЕ array_length. Изглеждат взаимозаменяеми и НЕ СА:
  --   array_length('{}', 1)        → NULL   (не 0!)
  --   NULL >= 1                    → NULL
  --   CHECK, дал NULL, се смята за ИЗПЪЛНЕН — Postgres отхвърля само FALSE.
  -- Тоест `check (array_length(recipients,1) >= 1)` пропуска точно случая,
  -- срещу който е писан, и остава мълчалива украса.
  --   cardinality('{}')            → 0
  --   0 >= 1                       → FALSE  → редът се отхвърля
  --
  -- Проверено на живо на 02.09.2026 с пробна таблица с ДВЕТЕ ограничения:
  -- вмъкване на '{}' мина през array_length варианта и падна на cardinality
  -- варианта с 23514. Пробната таблица е изтрита.
  constraint weekly_checklist_sends_recipients_chk
    check (cardinality(recipients) >= 1)
);

-- Табът чете ПОСЛЕДНАТА версия за показаната седмица — оттам и низходящият
-- ред на version в индекса.
create index if not exists weekly_checklist_sends_week_idx
  on public.weekly_checklist_sends (year, week_number, version desc);

