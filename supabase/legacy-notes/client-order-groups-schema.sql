-- Свързани клиентски заявки на един клиент (обща поръчка)
-- Един клиент често иска артикули от различни обекти -> магазинът пуска отделна
-- заявка към всеки изпълнител. group_id ги свързва в една поръчка.
-- Приложена в Supabase на 18.08.2026 (миграция: client_orders_group_id)

alter table client_orders add column if not exists group_id uuid;
create index if not exists idx_client_orders_group_id on client_orders(group_id);

-- Значение:
--   group_id - обща за всички заявки от една поръчка (NULL = самостоятелна заявка).
--              Няма отделна таблица "групи" - групата е просто общият uuid.
--
-- ВАЖНО: връзката е ИЗРИЧНА, не се извежда по телефон. В базата има телефони,
-- ползвани от различни клиенти (служебни/семейни), а имената на един и същ
-- човек са изписвани различно. Телефонът се ползва само за ПРЕДЛОЖЕНИЕ, което
-- човек потвърждава в интерфейса.
--
-- За справки: заявките от една група се приключват по различно време. Поръчката
-- е изпълнена едва когато ВСИЧКИ заявки с този group_id са в статус done.
