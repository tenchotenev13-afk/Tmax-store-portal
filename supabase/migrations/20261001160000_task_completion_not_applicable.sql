-- task_completions.status = 'not_applicable' — „Не се отнася за нас"
--
-- ЗАЩО. Обект, който физически няма нужното за задачата (стелажа, дисплея,
-- стоката), остава вечно неизпълнил: няма как да отметне нещо, което го няма,
-- а всяко друго състояние или го брои за свършено (лъжа), или го брои за
-- пропуснал (несправедливо). Третото състояние ИЗВАЖДА обекта от знаменателя —
-- 17/17, не 17/18 — и носи причината със себе си.
--
-- ВНИМАНИЕ към следващия: на status ИМА CHECK и той изброява стойностите.
-- task_completions_status_check беше CHECK (status = ANY (ARRAY['done',
-- 'postponed'])). Без тази миграция всеки запис с 'not_applicable' пада с
-- 23514 — тоест формата изглежда наред, а записът мълчи в конзолата.
-- Това е същият клас засада като политика, която изброява ключове
-- (виж CLAUDE.md, Сигурност): изброяването остарява тихо.
--
-- ПРИЧИНАТА Е ЗАДЪЛЖИТЕЛНА В ДАННИТЕ, не само във формата. Без нея редът е
-- „не се отнася, защото аз казвам" и след месец никой не помни защо един обект
-- е извън норма. Мин. 5 знака — толкова, колкото да отсее „не" и „-".
-- Съществуващите 'done' и 'postponed' редове НЕ се пипат: 3419 done (от тях
-- 1289 с коментар) и 5 postponed към 01.10.2026 остават валидни.
--
-- ОБХВАТ НА ЕДИН РЕД. Редът важи за ЗАДАЧАТА и ОБЕКТА, не за отделен ден:
--   · еднократна с няколко дни → всички дни;
--   · с прозорец → целият прозорец (затваря го като отметка);
--   · многоседмична → целият период;
--   · постоянна → СЕДМИЦАТА на реда, симетрично на отметката.
-- Датата в completion_date е денят на заявяването (както при отметка), а
-- четците сравняват с набора дати на задачата. Едно правило за всички видове —
-- различни правила по вид значи два кода, които се разминават (историята с
-- „Регионален" и с изключените обекти).
--
-- КОЙ ПИШЕ. Записът минава през tcUpsert() в клиента. Двата частични уникални
-- индекса (task_completions_uniq_task / _uniq_recurring) допускат ЕДИН ред на
-- (задача, обект, дата) и НЕ гледат статус, тоест N/A редът заема мястото и
-- последващо отмятане е PATCH, не INSERT — tcUpsert вече го прави.
--
-- АВТОМАТИЧНОТО ОТМЯТАНЕ не бива да пренаписва N/A. Проверено в базата:
--   · transit_sync_completions — `do update … where status = 'postponed'`,
--     тоест N/A ред не го докосва;
--   · transit_mark_empty_stores — `on conflict do nothing`, а изтриването е
--     само на редове с completed_by = 'auto:transit-empty'.
-- И двете са чисти БЕЗ промяна. Поправка иска само linkedTaskComplete() в
-- shared.js, която PATCH-ва всеки ред, различен от 'done'.
--
-- Rollback: 20261001160000_task_completion_not_applicable_down.sql

alter table public.task_completions
  drop constraint task_completions_status_check;

alter table public.task_completions
  add constraint task_completions_status_check
  check (status = any (array['done'::text, 'postponed'::text, 'not_applicable'::text]));

alter table public.task_completions
  add constraint task_completions_na_needs_reason_chk
  check (status <> 'not_applicable'
         or (comment is not null and length(btrim(comment)) >= 5));

comment on column public.task_completions.status is
  'done = изпълнена · postponed = отложена за друг ден (postponed_to) · not_applicable = „не се отнася за този обект" (причината е в comment, мин. 5 знака, и е ЗАДЪЛЖИТЕЛНА по CHECK). not_applicable изважда обекта от знаменателя: нито изпълнил, нито пропуснал. Един ред важи за цялата задача за този обект — всички дни, целия прозорец, целия период на многоседмичната, а при постоянна задача за седмицата на реда.';
