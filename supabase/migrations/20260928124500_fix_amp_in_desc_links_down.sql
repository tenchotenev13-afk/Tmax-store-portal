-- ⚠ ОБРАТНИЯТ ХОД Е ПО-ГРУБ ОТ ПОПРАВКАТА. Поправката пипа само `&amp;`, което
-- по построение се среща единствено в адреса; тук няма как да се различи кой `&`
-- е бил ескейпнат и кой не, затова се ескейпва ВСЯКО `&` в описанието.
-- Към 28.09.2026 в трите реда няма друг `&` освен тези в адресите, значи ходът е
-- точен. Допише ли някой текст с `&` след поправката, обратният ход ще промени и
-- него.
--
-- Следствие: това е АВАРИЙНО връщане (ако се окаже, че някъде се е чакал
-- ескейпнатият вид), не рутинна операция. Преди да се пусне — сверявай
-- съдържанието на трите реда, не само id-тата.
--
-- Обратният ред НЕ е важен: трите UPDATE-а не зависят един от друг.

update bulletin_tasks
   set description = replace(description, '&', '&amp;')
 where id = '9a7f1104-55d0-47b8-8b19-0a39857eb7e3'
   and description like '%&%'
   and description not like '%&amp;%';

update recurring_task_versions
   set description = replace(description, '&', '&amp;')
 where id in ('22e9a61f-bb61-410d-afbb-6f6eaac698ab',
              '1919a8dd-ebfd-4e35-84cc-bcac80e0eff8')
   and description like '%&%'
   and description not like '%&amp;%';
