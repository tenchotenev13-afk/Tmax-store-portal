-- Измерено (02.10.2026): 51 невзети реда, създадени от офиса/импорта, имат
-- confirmed_date; 32 от тях са с дата ПО-РАННА от създаването на реда, тоест
-- дошла от файла. Пряко число за презаписванията няма — няма одитна следа и
-- backup_snapshots не включва stock_returns. Оттук нататък има.
--
-- Стойности: 'store:<обект>' | 'office:<име>' | 'import:<име>'. Пишат се САМО
-- когато датата наистина се променя. NULL = заварен ред; правилото не го брои.
--
-- Rollback: 20261002090000_stock_returns_confirmed_by_down.sql

