-- bulletin_tasks.due_window — прозорец за изпълнение и при ЕДНОКРАТНА задача
--
-- ЗАЩО. Еднократна задача с няколко дни (due_dates) искаше отметка за ВСЕКИ ден
-- поотделно — така е от въвеждането на многодневните („Всеки ден се отмята
-- ОТДЕЛНО", bulletin.js:613). За „изложи палето зоната до събота" това е
-- грешно: свършена в четвъртък е свършена. Измерено на С39 „Излагане палето
-- зони" (4 дни): 15 от 18 обекта излизат под 4/4, а само три с четири отметки —
-- задачата е свършена, броячът иска четири щраквания.
--
-- Колоната е ОГЛЕДАЛО на recurring_tasks.due_window (24.08.2026) и правилото е
-- същото: последният ден е СРОКЪТ, предходните са „разрешено по-рано", и една
-- отметка където и да е в прозореца затваря задачата. completion_date носи
-- РЕАЛНИЯ ден на щракване, а четците сравняват с целия набор дати — една
-- конвенция за двата вида задачи, не втора.
--
-- СЪЩЕСТВУВАЩИТЕ ОСТАВАТ false. Към 01.10.2026: 65 задачи общо, 8 с повече от
-- един ден (от тях 1 notice), нито една многоседмична. Миналото не се пипа —
-- отчетите за онези седмици вече са излезли.
--
-- CHECK-ът пази инварианта в ДАННИТЕ, не само във формата: прозорец без поне два
-- дни е безсмислица. Многоседмичната е покрита транзитивно — за нея
-- bulletin_tasks_spans_single_day_chk вече изисква cardinality(due_dates) <= 1,
-- тоест прозорец и spans_from не могат да съжителстват. Кодът пък ИГНОРИРА
-- стойността извън 2..6 дни (taskIsWindow), както прави и recurringIsWindow —
-- така ред, дошъл отнякъде другаде, не мени поведението мълчаливо.
--
-- Rollback: 20261001120000_bulletin_task_due_window_down.sql

alter table public.bulletin_tasks
  add column due_window boolean not null default false;

alter table public.bulletin_tasks
  add constraint bulletin_tasks_window_needs_days_chk
  check (due_window = false or coalesce(cardinality(due_dates), 0) > 1);

comment on column public.bulletin_tasks.due_window is
  'Прозорец за изпълнение: при няколко дни в due_dates последният е срокът, предходните са „разрешено по-рано", и ЕДНА отметка където и да е в прозореца затваря задачата. Огледало на recurring_tasks.due_window. completion_date носи реалния ден на щракване.';
