-- ── 2. UPDATE (една транзакция, гард по броя) ──────────────────────────────
do $$
declare n int;
begin
  with upd as (
    update public.stock_differences d
       set created_by = r.submitted_by
      from public.differences_reports r
     where r.id = d.report_id
       and d.created_by is distinct from r.submitted_by
    returning 1
  ) select count(*) into n from upd;
  if n <> 290 then
    raise exception 'stock-diff-created-by-fix: очаквани 290 реда, засегнати % — нищо не е записано', n;
  end if;
end $$;

