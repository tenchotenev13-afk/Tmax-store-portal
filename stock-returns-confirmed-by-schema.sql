-- КОЙ и КОГА е поставил „Дата потвърдена актуализация" (stock_returns).
--
-- ⚠ ПОДГОТВЕНО, НЕ Е ПРИЛОЖЕНО към 02.10.2026 — чака потвърждение.
-- Миграция: supabase/migrations/20261002..._stock_returns_confirmed_by.sql
--
-- ЗАЩО
-- Автоматичното отмятане на постоянната задача „СРОК НА ГОДНОСТ/РЕКЛАМАЦИИ"
-- (виж stock-returns-auto-complete-schema.sql) брои обекта за изпълнил, когато
-- всичките му НЕВЗЕТИ записи имат актуализация в прозореца на седмицата. Но
-- confirmed_date се пише по ЧЕТИРИ пътя и само един от тях е обектът:
--
--   1. ръчната форма (sr-cdate)            — обектът ИЛИ офисът, 1 ред;
--   2. импорт „По разлики"                 — САМО офисът (бутонът е зад
--      (SR_DIFF_LIST_COLS, колона          canAddSR: admin/accounting/
--      „ДАТА НА ПОТВЪРДЕНА АКТУАЛИЗАЦИЯ")  logistics), целият файл, и
--                                            ПРЕЗАПИСВА съществуващи редове;
--   3. многолистов ERP импорт              — същите роли; там празна клетка
--      (updFromFile)                         дори ИЗТРИВА датата (nz → NULL,
--                                            „файлът е авторитетен");
--   4. единичен гъвкав лист                — познат ПВ-ЕВР се пропуска.
--
-- Без тези две колони качването на файла от офиса в сряда сутрин щеше да
-- „отметне" обектите, без те да са пипнали нищо — тоест автоматиката щеше да
-- произведе същата лъжа като ръчната отметка, само по-бързо.
--
-- РИСКЪТ Е ИЗМЕРЕН, доколкото данните позволяват (02.10.2026). Пряко число
-- НЯМА: няма одитна следа, няма updated_at, а дневното резервно копие
-- (backup_snapshots) НЕ включва stock_returns. Косвено:
--   · 51 невзети реда, създадени от офиса/импорта, вече имат confirmed_date;
--   · от тях 32 са с дата ПО-РАННА от създаването на самия ред — такава дата
--     може да е дошла само от файла, не от обекта;
--   · последният импорт (01.10) е създал 3 невзети реда, нито един с дата.
-- Плюс самият код: toUpdate пише confirmed_date на ВСЕКИ съвпаднал ред при
-- ВСЕКИ импорт. Презаписването е по дизайн.
-- След тази миграция въпросът става измерим занапред — точно затова колоните
-- са две, а не една.
--
-- КАКВО ПИШЕ ВСЕКИ ПЪТ (решение на Тенчо, 02.10.2026)
--   · форма, когато влезлият е потребител на ОБЕКТА на реда
--     (currentUser.store_name === row.store_name) → 'store:<обект>';
--   · форма от офиса (всяка друга роля)           → 'office:<име>';
--   · импорти 2 и 3, на всеки ред, на който сменят датата, ВКЛЮЧИТЕЛНО когато
--     я изтриват (NULL)                            → 'import:<име>';
--   · датата НЕ се променя → колоните НЕ се пипат (иначе всеки импорт би
--     „освежавал" чужда актуализация и следата би станала безполезна).
--
-- ПРАВИЛОТО брои ред за актуализиран САМО при
--   confirmed_by = 'store:' || store_name  И  confirmed_date в прозореца.
-- Заварените редове (confirmed_by NULL) НЕ се броят. На практика това не мени
-- нищо: датите им са от минали седмици и без това падат извън прозореца.
--
-- БЕЗ CHECK и БЕЗ тригер за попълване. Стойността идва от клиента, защото само
-- той знае КОЙ е влязъл; тригер в базата вижда anon ключа и за трите пътя.
-- Форматът ('store:'/'office:'/'import:') се пази от теста, не от базата —
-- CHECK по префикс би спрял и бъдещ пети път, вместо да го накара да се обяви.

alter table public.stock_returns
  add column if not exists confirmed_by text,
  add column if not exists confirmed_at timestamptz;

comment on column public.stock_returns.confirmed_by is
  'Кой постави/смени „Дата потвърдена актуализация": store:<обект> (ръчната форма от потребител на самия обект), office:<име> (ръчната форма от офиса), import:<име> (двата Excel импорта, включително когато ИЗТРИВАТ датата). NULL = ред отпреди 02.10.2026 или дата, пипана по непокрит път. Автоматичното отмятане на „СРОК НА ГОДНОСТ/РЕКЛАМАЦИИ" брои САМО store:<същия обект> — иначе файл от офиса би отметнал обекта, без той да е работил.';

comment on column public.stock_returns.confirmed_at is
  'Кога е поставена/сменена confirmed_date. Пише се заедно с confirmed_by и САМО когато датата наистина се променя — иначе всеки импорт би „освежавал" чужда актуализация и следата би станала безполезна.';

