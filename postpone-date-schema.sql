-- Отлагане с точна дата: task_completions.postponed_to
--
-- Досега „⏱ Отложи" записваше ред status='postponed' с причина и
-- completion_date = ПЪРВОНАЧАЛНИЯ срок. Нямаше „за кого", тоест задачата не
-- се връщаше никъде: нито в „Днес", нито в известията, нито в следващата
-- седмица. Единствената ѝ следа беше списъкът „Отложени" в отчета.
-- postponed_to е денят, за който е уговорена.
--
-- ═══ ЕДИН РЕД НА (ЗАДАЧА, ОБЕКТ, ДЕН) ═══════════════════════════════════
-- task_completions_uniq_task / _uniq_recurring пазят по един ред за
-- (задача, обект, completion_date). Затова отлагането и изпълнението на
-- ОРИГИНАЛНОТО явяване са СЪЩИЯТ ред: на новата дата статусът става 'done',
-- completion_date остава ПЪРВОНАЧАЛНАТА (ключът за отчетите не се мени), а
-- postponed_to остава записан. От това следват две неща, които кодът ползва:
--   · отчетът различава „отложена, изпълнена" от обикновена отметка;
--   · „✓ със закъснение" се мери срещу postponed_to, не срещу срока.
-- Когато новият ден е И собствено явяване на задачата (постоянна задача,
-- пренесена в ден, в който тя и без това е дължима), сляният ред на екрана
-- пише ДВА реда: стария (postponed→done, оригинален completion_date) и нов
-- done за новия ден. Различният completion_date ги прави допустими за
-- двата уникални индекса.
--
-- ═══ ОГРАНИЧЕНИЯТА ══════════════════════════════════════════════════════
--   postponed_to_req_chk — отложен ред без дата е точно старото състояние,
--     което оправяме. NOT VALID: трите заварени реда (виж по-долу) остават
--     с NULL и не се пренаписват; всеки НОВ или обновен ред минава проверка.
--     Следствие по дизайн: UPDATE върху стар отложен ред, който го оставя
--     'postponed' без дата, ще бъде отказан — точно каквото искаме.
--   postponed_to_after_chk — датата е СЛЕД срока. VALID от първия ден:
--     всички заварени редове са с postponed_to IS NULL и минават.
--     Клонът completion_date IS NULL е за старите записи без ден.
--
-- ═══ ЗАВАРЕНИТЕ ДАННИ (правило 9, проверено 12.09.2026) ═════════════════
-- Отложени редове: 3, всичките от бюлетина, всичките със completion_date
-- 2026-08-31 (С36) и с попълнен коментар; нито един няма ред „изпълнена".
--   Петрич · Брак и консумативи м.08
--   Петрич · Присъствени форми      (коментар: „Уговорка с Ваня - 04.09.2026")
--   Троян  · Промоция Латекс КС
-- Backfill completion_date + 1 НЕ се прави: за „Присъствени форми"
-- уговорката е била 04.09, не 01.09, тоест дата от догадка щеше да е
-- невярна; освен това седмичният отчет за С36 вече е изпратен и backfill
-- би го променил при повторно изчисляване. Решено 12.09.2026: NULL значи
-- „отложена без дата" и се държи по старому — вижда се в стария ден и не
-- се връща никъде.
--
-- Засегнати съществуващи редове: 0 (нова колона, NULL по подразбиране).
--
-- Нова колона → Живко обновява mirror-schema.sql и $TableColumns.
-- Rollback: 20260912152519_postpone_date_down.sql

alter table public.task_completions
  add column postponed_to date;

alter table public.task_completions
  add constraint task_completions_postponed_to_req_chk
  check (status <> 'postponed' or postponed_to is not null) not valid;

alter table public.task_completions
  add constraint task_completions_postponed_to_after_chk
  check (postponed_to is null or completion_date is null or postponed_to > completion_date);

-- Бюлетинът на седмица W тегли пренесените в нея задачи:
--   status=eq.postponed&postponed_to=gte.<пон>&postponed_to=lte.<нед>
create index tc_postponed_to_idx
  on public.task_completions (postponed_to)
  where status = 'postponed';

comment on column public.task_completions.postponed_to is
  'Денят, за който е отложена задачата (NULL = стар ред без дата). completion_date остава първоначалният срок; при изпълнение същият ред става status=done, а postponed_to се пази.';
