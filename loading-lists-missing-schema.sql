-- loading-lists-missing-schema.sql
-- Пакет А по товарните листи: „Неполучен" по ред + приключване от обекта +
-- статус „Частично приключен".
-- ПРИЛОЖЕНО В СУПАБЕЙС НА 20.09.2026 (миграция 20260920142158_loading_missing).
-- Този файл е ОГЛЕДАЛО на живата схема, не източник: сверен е след
-- прилагането срещу pg_get_constraintdef и information_schema.columns.
-- Допълва loading-lists-schema.sql — двата се четат ЗАЕДНО.
--
-- ЗА КАКВО СЛУЖИ
-- Дотук редът имаше само received true/false и неотметнатият ред значеше
-- „още не е дошъл". Обектът нямаше как да каже „това НЕ дойде" — значи и
-- нямаше как да приключи приемането си с липси, а листът ставаше done само
-- когато ВСИЧКИ редове на ВСИЧКИ обекти са получени. Лист с един липсващ
-- палет висеше „изпратен" завинаги и никой не научаваше нищо.
--
-- ТРИТЕ СЪСТОЯНИЯ НА ЕДИН РЕД
--   received = false, missing = false -> чака (камионът още не е дошъл)
--   received = true                   -> прието
--   missing  = true                   -> обектът ЗАЯВЯВА, че не е пристигнало
-- Третото е твърдение, не отсъствие на отметка. Затова клиентът изисква
-- непразен store_comment, преди да го запише: „неполучено" без обяснение е
-- толкова безполезно, колкото и празен ред.
--
-- ВЗАИМНОТО ИЗКЛЮЧВАНЕ НЕ Е CHECK — НАРОЧНО
-- received и missing не могат да са едновременно true, но базата НЕ го
-- налага. Огледалото на Живко копира редове през PostgREST; CHECK от негова
-- страна би отхвърлял редове, които в Supabase са минали, и синхронизацията
-- би спряла мълчаливо. Правилото живее в клиента (llMarkReceived /
-- llMarkMissing в loading.js). Следствие, което трябва да се знае: всяка
-- справка „колко са неполучените" пише `missing and not received`, а не само
-- `missing`.
--
-- ДВЕТЕ ЗНАЧЕНИЯ НА ДУМАТА „PARTIAL" — НЕ СЕ ИЗВЕЖДАТ ЕДНО ОТ ДРУГО
--   loading_list_items.partial (03.09.2026) = „с този товар тръгва само ЧАСТ
--     от стоковия документ"; пази goods_transit да не се затвори.
--   loading_lists.status = 'partial' (тук) = „листът е приключен, но част от
--     редовете са заявени като неполучени".
-- Едната е за документ, другата за лист. Очаквай объркване при четене.

-- ---------------------------------------------------------------------
-- 1. Трите нови колони по реда
-- ---------------------------------------------------------------------
-- Огледални на received / received_by / received_at, включително това, че се
-- пълнят от КЛИЕНТА в момента на маркирането — тригер няма и няма да има.
alter table public.loading_list_items
  add column if not exists missing    boolean not null default false,
  add column if not exists missing_by text,
  add column if not exists missing_at timestamptz;

comment on column public.loading_list_items.missing is
  'Обектът заявява, че редът НЕ е пристигнал. Огледално на received и взаимно изключващо се с него — но БЕЗ check в базата (огледалото на Живко копира редове през PostgREST); правилото живее в клиента (loading.js).';
comment on column public.loading_list_items.missing_by is
  'Кой е маркирал реда като неполучен. Пълни се от клиента в момента на маркирането — тригер няма, както при received_by.';
comment on column public.loading_list_items.missing_at is
  'Кога е маркиран като неполучен. Пълни се от клиента заедно с missing_by.';

-- Индекс по (store_name, missing) НЯМА. Заварената заявка на магазинската
-- страна тегли всички редове на обекта наведнъж и филтрира в клиента; само
-- notifications.js пита с received=eq.false&missing=eq.false и попада в
-- loading_list_items_store_idx (store_name, received). Нов индекс е отделно
-- решение — и нещо, което Живко също трябва да отрази.

-- ---------------------------------------------------------------------
-- 2. Новата стойност на status
-- ---------------------------------------------------------------------
-- Отделен статус, а не done с бележка: складът търси точно тези листи, а в
-- done те биха се смесили с приетите без забележка.
-- Разширяването е надмножество на старото, тоест не може да обезсили нито
-- един заварен ред.
alter table public.loading_lists
  drop constraint if exists loading_lists_status_check;

alter table public.loading_lists
  add constraint loading_lists_status_check
    check (status in ('draft', 'sent', 'done', 'partial'));

comment on column public.loading_lists.status is
  'draft | sent | done | partial. draft е видим само за склада; от sent нататък обектите виждат своите редове. partial = приключен лист, в който има редове с missing = true.';

-- ГЕЙТЪТ НА МАГАЗИНСКАТА СТРАНА СЕ ПРОМЕНЯ ЗАЕДНО С ТОВА.
-- llLoadStoreSide() в loading.js чете status=in.(sent,done,partial). Остане ли
-- само (sent,done), приключеният с липси лист става НЕВИДИМ за обекта точно в
-- мига, в който той го приключва — тоест собствената му заявка за липса
-- изчезва от екрана му.

