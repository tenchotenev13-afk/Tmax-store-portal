-- task-completion-not-applicable-schema.sql
-- „🚫 Не се отнася за нас" — трето състояние на отмятането.
-- Приложено в Supabase (xiwkdiqqplgdcrkewgtv) на 01.10.2026.
-- Миграция: 20261001160000_task_completion_not_applicable
-- Rollback:  supabase/migrations/20261001160000_task_completion_not_applicable_down.sql
--
-- ЗАЩО
-- Обект, който физически няма нужното за задачата (стелажа, дисплея, стоката),
-- остава вечно неизпълнил. Досегашните две състояния не му помагат: „изпълнена"
-- е лъжа, „отложена" значи „ще го направя после", а липсата на ред значи
-- „пропуснал". Третото състояние казва истината — задачата НЕ ВАЖИ за този
-- обект — и го ИЗВАЖДА от знаменателя: 17/17, не 17/18.
--
-- БЕЗ НОВА КОЛОНА. Причината живее в task_completions.comment, който вече се
-- чете и показва навсякъде (renderCompletionExtras, седмичния отчет, отчета по
-- задача). Нова колона значи ново поле за претърсване по т.7 от процеса и нов
-- ред в огледалото — за нищо.
--
-- ⚠ ЗАСАДАТА, която заданието не очакваше: на status ИМА CHECK и той ИЗБРОЙВА
-- стойностите. Преди миграцията:
--   task_completions_status_check CHECK (status = ANY (ARRAY['done','postponed']))
-- Тоест без DDL всеки запис с 'not_applicable' пада с 23514 — формата изглежда
-- наред, а записът мълчи. Същият клас засада като политика, която изброява
-- ключове (CLAUDE.md, Сигурност): изброяването остарява тихо.
--
-- ДВЕТЕ ОГРАНИЧЕНИЯ
--   task_completions_status_check
--     check (status = any (array['done','postponed','not_applicable']))
--   task_completions_na_needs_reason_chk
--     check (status <> 'not_applicable'
--            or (comment is not null and length(btrim(comment)) >= 5))
--
-- Причината е задължителна В ДАННИТЕ, не само във формата. Без нея редът е
-- „не се отнася, защото аз казвам" и след месец никой не помни защо един обект
-- е извън норма. Мин. 5 знака — толкова, колкото да отсее „не", „-" и „ня".
-- Проверено с реални вмъквания, върнати с rollback (01.10.2026):
--   с причина „няма такъв стелаж в обекта" → мина
--   без коментар                          → 23514
--   коментар „  ня  " (4 знака след trim)  → 23514
--   status 'kakvoto_i_da_e'                → 23514
--   'done' без коментар                    → мина (старото поведение е цяло)
--
-- СЪСТОЯНИЕ НА ДАННИТЕ към 01.10.2026 (преди и след миграцията)
--   done           3419 реда (от тях 1289 с коментар)
--   postponed         5
--   not_applicable    0
-- Старите редове не се пипат; миграцията само разширява допустимото.
--
-- ОБХВАТ НА ЕДИН РЕД — важи за ЗАДАЧАТА и ОБЕКТА, не за отделен ден:
--   · еднократна с няколко дни → всички дни;
--   · с прозорец              → целият прозорец (затваря го като отметка);
--   · многоседмична           → целият период;
--   · постоянна               → СЕДМИЦАТА на реда, симетрично на отметката.
-- completion_date носи деня на ЗАЯВЯВАНЕТО (както при отметка), а четците
-- сравняват с набора дати на задачата. Едно правило за всички видове — две
-- правила по вид значат два кода, които се разминават (историята с „Регионален"
-- и със списъците изключени обекти).
--
-- За постоянна задача това значи, че обект без стелажа ще заявява наново всяка
-- седмица. Нарочно: recurring_task_skips също е по седмица (year+week_number),
-- тоест не решава нищо друго, освен да прехвърли повторението на офиса.
-- ПОСТОЯННОТО изключване на обект е target_stores с редакция „От тази седмица
-- нататък" — отговорност на офиса, не нов механизъм.
--
-- КОЙ ПИШЕ. Записът минава през tcUpsert() в клиента. Двата частични уникални
-- индекса (task_completions_uniq_task / _uniq_recurring) допускат ЕДИН ред на
-- (задача, обект, дата) и НЕ гледат статус: N/A редът заема мястото, тоест
-- последващо отмятане е PATCH, не INSERT — tcUpsert вече го прави.
--
-- АВТОМАТИЧНОТО ОТМЯТАНЕ не бива да пренаписва N/A. Проверено в базата, не
-- предположено:
--   · transit_sync_completions — `do update … where status = 'postponed'`,
--     тоест N/A ред не го докосва. БЕЗ промяна.
--   · transit_mark_empty_stores — `on conflict do nothing`, а изтриването е
--     само на редове с completed_by = 'auto:transit-empty'. БЕЗ промяна.
--   · linkedTaskComplete() в shared.js PATCH-ваше ВСЕКИ ред, различен от
--     'done' (писано за отложените). ТОВА се поправи: N/A се третира като
--     'done' и се пропуска.
-- Други SQL функции, които пишат в task_completions, няма — проверено през
-- pg_proc срещу pg_get_functiondef.
--
-- ОГЛЕДАЛО (Живко): НЯМА нова колона и няма нова таблица. Промяната е само в
-- допустимите стойности на task_completions.status — огледалото копира
-- стойността както е, значи sync-mirror.ps1 не иска промяна. Текстът го праща
-- Тенчо.

alter table public.task_completions
  drop constraint task_completions_status_check;

alter table public.task_completions
  add constraint task_completions_status_check
  check (status = any (array['done'::text, 'postponed'::text, 'not_applicable'::text]));

alter table public.task_completions
  add constraint task_completions_na_needs_reason_chk
  check (status <> 'not_applicable'
         or (comment is not null and length(btrim(comment)) >= 5));

comment on column public.task_completions.status is
  'done = изпълнена · postponed = отложена за друг ден (postponed_to) · not_applicable = „не се отнася за този обект" (причината е в comment, мин. 5 знака, и е ЗАДЪЛЖИТЕЛНА по CHECK). not_applicable изважда обекта от знаменателя: нито изпълнил, нито пропуснал. Един ред важи за цялата задача за този обект — всички дни, целия прозорец, целия период на многоседмичната, а при постоянна задача за седмицата на реда.';
