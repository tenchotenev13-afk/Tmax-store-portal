-- weekly-checklist-deadline-day.sql
-- Срок в рамките на месеца за показател от чек листа.
-- НЕ Е ПРИЛОЖЕНО. Прилага се ръчно след преглед.
--
-- ЗАЩО Е НУЖНО
-- „Стока на път" се пълни от goods_transit, а таблицата НЕ се натрупва:
-- изтрива се и се зарежда наново при всеки месечен импорт (всичките 2269
-- записа към 02.09.2026 са от 01.09.2026, вкарани за осем секунди — оттам и
-- това, че created_at не носи никаква информация за обекта). Цвети качва
-- снимката до 3-то число, обектът я актуализира до 10-то.
--
-- Следствието е, че между 1-во и 10-то „52/190" НЕ Е ОЦЕНКА, а междинно
-- състояние: срокът още тече. Показано наравно с останалите числа, то се
-- чете като провал на обекта и то точно в дните, когато той е в правото си
-- още да не е започнал.
--
-- ЗАЩО КОЛОНА, А НЕ ПРОВЕРКА В КОДА
-- Прагът е свойство на ПОКАЗАТЕЛЯ, не на рендирането. Следващите показатели
-- ще имат свои срокове (или никакъв), а закована проверка „ако е стока на
-- път и днес е преди 10-то" значи, че всеки следващ срок иска промяна по
-- код. Тук е ред в базата, както са и label, value_type и source.
--
-- NULL = НЯМА ТАКЪВ СРОК, тоест показателят никога не е „още рано".
-- Това е стойността по подразбиране и остава за петте останали показателя:
-- четири от тях са седмични (постоянни задачи и каса) и месечен праг би бил
-- безсмислен за тях.

alter table public.weekly_checklist_metrics
  add column if not exists deadline_day int;

comment on column public.weekly_checklist_metrics.deadline_day is
  'Ден от месеца, до който включително срокът още тече. Дотогава стойността се показва като междинна, не като оценка. NULL = няма такъв срок.';

-- Прагът е ден от месеца, не дата. 28 нарочно, а не 31: срок след 28-мо не
-- може да се спази през февруари и мълчаливо би значел „никога не изтича".
alter table public.weekly_checklist_metrics
  drop constraint if exists weekly_checklist_metrics_deadline_day_chk;
alter table public.weekly_checklist_metrics
  add constraint weekly_checklist_metrics_deadline_day_chk
  check (deadline_day is null or deadline_day between 1 and 28);

-- Единственият показател със срок към 02.09.2026.
update public.weekly_checklist_metrics
   set deadline_day = 10
 where key = 'stoka_na_pat';

