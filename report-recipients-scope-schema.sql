-- report-recipients-scope-schema.sql
-- Обхват по обекти за получател на ОБЩИЯ дневен репорт.
-- Приложено в Supabase (xiwkdiqqplgdcrkewgtv) на 08.09.2026.
--
-- ЗАЩО
-- Дневният отчет имаше два списъка: report_recipients (пълният отчет за
-- цялата верига, едно писмо в общо поле "to") и регионалните от
-- users.is_regional (личен отчет само за assigned_stores). Между двете
-- нямаше нищо: човек, който трябва да получава дневния на ЕДИН обект, без
-- да е регионален, нямаше как да бъде описан.
--
-- КАК СЕ ЧЕТЕ КОЛОНАТА (send-scheduled-report/index.ts, v17)
--   NULL или празен масив = пълният отчет, както досега;
--   непразен масив        = получателят ИЗЛИЗА от общото "to" и получава
--                           ЛИЧЕН отчет само за изброените обекти.
-- Обхватът важи САМО за дневния. При седмичния колоната се пренебрегва и
-- получателят си остава в общото писмо — иначе би изпаднал и оттам, без
-- това да е поискано.
--
-- ЗАЩО text[], А НЕ ВРЪЗКА КЪМ ТАБЛИЦА С ОБЕКТИ
-- Обектите в целия портал се носят като имена (users.store_name,
-- users.assigned_stores, bulletin_tasks.target_stores). Отделна таблица
-- няма. Колоната следва assigned_stores буква по буква, за да може
-- събирачът на отчета да приеме двата обхвата по един и същи начин.
--
-- ГРАНТОВЕ: НЕ СА НУЖНИ. report_recipients е с ТАБЛИЧНИ права за anon и
-- authenticated (за разлика от users, която от 24.08.2026 е с колонни) —
-- новата колона ги наследява. Проверено на 08.09.2026: anon има
-- SELECT/INSERT/UPDATE върху scope_stores.

alter table public.report_recipients
  add column if not exists scope_stores text[] null;

comment on column public.report_recipients.scope_stores is
  'Обхват по обекти за ДНЕВНИЯ отчет. NULL/празно = пълният отчет (общо "to"); непразно = личен отчет само за тези обекти. Седмичният го пренебрегва.';

