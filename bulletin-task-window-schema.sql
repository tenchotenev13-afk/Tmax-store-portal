-- bulletin-task-window-schema.sql
-- Прозорец за изпълнение при ЕДНОКРАТНА задача с няколко дни.
-- Приложено в Supabase (xiwkdiqqplgdcrkewgtv) на 01.10.2026.
-- Миграция: 20261001120000_bulletin_task_due_window
-- Rollback: supabase/migrations/20261001120000_bulletin_task_due_window_down.sql
--
-- ЗАЩО
-- Еднократната задача с няколко дни в due_dates искаше отметка за ВСЕКИ ден
-- поотделно — така е от въвеждането на многодневните („Всеки ден се отмята
-- ОТДЕЛНО", bulletin.js:613). За „изложи палето зоната до събота" това е грешно:
-- свършена в четвъртък е свършена.
--
-- Измерено, не предположено. С39 „Излагане палето зони" (4 дни, 23–26.09):
--   4/4 отметки → 3 обекта
--   3/4          → 9
--   2/4          → 3
--   1/4          → 3  (Габрово, Монтана, Раднево)
-- Тоест 15 от 18 обекта излизат под норма при свършена работа.
--
-- КОЛОНАТА
--   bulletin_tasks.due_window boolean not null default false
-- Огледало на recurring_tasks.due_window (24.08.2026). Правилото е ЕДНО и също
-- за двата вида задачи:
--   · последният ден от due_dates е СРОКЪТ;
--   · предходните са „разрешено по-рано";
--   · една отметка където и да е в прозореца затваря задачата за седмицата;
--   · задачата е ЕДИН елемент в знаменателя, не N.
--
-- completion_date носи РЕАЛНИЯ ден на щракване, не срока. Четците сравняват с
-- целия набор дати на прозореца (както recurringWindowComp). Нарочно НЕ се
-- нормализира към последния ден: това щеше да е втора конвенция за „кога е
-- изпълнено" в един модул (многоседмичната пише срока) и щеше да загуби кога
-- наистина е свършена работата — а при photo/comment задачите точно този ден
-- обяснява снимките.
--
-- ОГРАНИЧЕНИЕТО
--   bulletin_tasks_window_needs_days_chk
--   check (due_window = false or coalesce(cardinality(due_dates), 0) > 1)
-- Инвариантът е в ДАННИТЕ, не само във формата: прозорец без поне два дни е
-- безсмислица. Проверено, че отказва — един ден и „без дни" дават
-- check_violation, два дни минават.
-- Многоседмичната е покрита ТРАНЗИТИВНО: за нея bulletin_tasks_spans_single_day_chk
-- вече изисква cardinality(due_dates) <= 1, тоест прозорец и spans_from не могат
-- да съжителстват. Втора клауза тук би била излишна и само би карала следващия да
-- се чуди защо са две.
-- Кодът отделно ИГНОРИРА стойността извън 2..6 дни (taskIsWindow), точно както
-- recurringIsWindow — ред, дошъл отнякъде другаде, не мени поведението мълчаливо.
--
-- СЪСТОЯНИЕ НА ДАННИТЕ към 01.10.2026 (преди и след миграцията)
--   задачи общо: 65
--   с cardinality(due_dates) > 1: 8   (от тях 1 notice, 0 многоседмични)
--   с due_window = true: 0
-- Съществуващите остават false — миналото не се пипа, отчетите за онези седмици
-- вече са излезли. Включването е решение на човек, по задача.
--
-- NOTICE
-- „Само за информация" няма отметка, тоест прозорец не ѝ значи нищо: формата не
-- го показва и кодът не го прилага. Колоната може да е true на notice ред само
-- ако е сложена ръчно — taskIsWindow() не го зачита.
--
-- AUTO_COMPLETE
-- Автоматичното отмятане (linked_module + auto_complete) изисква ТОЧНО ЕДИН ден
-- срок (bulAutoCompleteValid). Прозорец и автоматично отмятане не се комбинират и
-- това НЕ се променя тук.
--
-- ОГЛЕДАЛО (Живко): нова КОЛОНА в съществуваща таблица. Виж текста в отчета.

alter table public.bulletin_tasks
  add column due_window boolean not null default false;

alter table public.bulletin_tasks
  add constraint bulletin_tasks_window_needs_days_chk
  check (due_window = false or coalesce(cardinality(due_dates), 0) > 1);

comment on column public.bulletin_tasks.due_window is
  'Прозорец за изпълнение: при няколко дни в due_dates последният е срокът, предходните са „разрешено по-рано", и ЕДНА отметка където и да е в прозореца затваря задачата. Огледало на recurring_tasks.due_window. completion_date носи реалния ден на щракване.';
