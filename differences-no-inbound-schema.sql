-- differences-no-inbound-schema.sql
-- Отметка „Няма входяща доставка в системата" върху public.differences_reports.
-- Разлики, етап 4 (среща 12.11.2026, уточнение на Тенчо 17.11.2026).
-- Приложено в Supabase (xiwkdiqqplgdcrkewgtv) на 17.11.2026,
-- миграция differences_reports_no_inbound (версия 20261117095851).
--
-- ЗАЩО
-- Стоката е дошла с документ, но в SAP няма входяща доставка, по която
-- обектът да я заприходи. Цвети трябва да го разбере веднага (известие до
-- групата „Разлики"), а в картата, печата и Excel-а се вижда бадж
-- „📭 Няма входяща". В имейла до доставчика НЕ влиза — вътрешна информация
-- за SAP.
--
-- Има смисъл само при посока „Доставчик" и се изключва взаимно с
-- no_document („📄 Стоката е без документ"). Поръчката и стоковата остават
-- задължителни (правилата от етап 3). При междускладов и сторна по грешен
-- прием отметката не се рисува и стойността остава false.
--
-- ЗАЩО NOT NULL DEFAULT FALSE
-- Като no_document: клиентът пише винаги булева стойност, „не знам" няма.
-- Default false покрива заварените бланки.
--
-- ГРАНТ НЕ Е НУЖЕН
-- differences_reports има ТАБЛИЧЕН грант за anon
-- (relacl = anon=arwdDxtm/postgres, проверено 17.11.2026), тоест новата
-- колона се покрива автоматично.

alter table differences_reports
  add column if not exists no_inbound boolean not null default false;

comment on column differences_reports.no_inbound is
  'Обектът е отбелязал, че в системата няма входяща доставка за стоката (само посока доставчик)';

