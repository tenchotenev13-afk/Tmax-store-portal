-- bus-routes-date-shift-schema.sql
-- Изместване на bus_routes.route_date с +1 ден — данни, НЕ схема.
-- Прилага се ЗАЕДНО с поправката в calendar.js (localDateISO вместо
-- toISOString): миграцията веднага преди push-а, push-ът веднага след нея.
--
-- ЗАЩО
-- До 13.09.2026 calendar.js строеше датите на МЕСТНА полунощ (getWeekDates →
-- setHours(0,0,0,0)) и ги режеше с toISOString().slice(0,10). В България
-- (UTC+2/+3) местната полунощ в UTC е предният ден — и то ПО ЦЯЛ ДЕН, не само
-- нощем. Модалът „+ Добави маршрут" предлага понеделник–петък, но записва
-- стойността на опцията, тоест всеки маршрут е влизал с ДЕН ПО-РАНО:
-- понеделник → неделя, петък → четвъртък.
--
-- Доказателство към 13.09.2026 (133 реда, created_at 15.06 – 08.09.2026):
--   dow 0 (неделя)  25   ← трябва да са понеделници
--   dow 1..4        108
--   dow 5 (петък)   0    ← нито един петък за три месеца
--   dow 6 (събота)  0
-- Календарът изглеждаше наред, защото и записът, и показването бяха изместени
-- еднакво. Транспортните и клиентските заявки обаче носят истински дати и
-- излизаха в колоната на СЛЕДВАЩИЯ ден.
--
-- bus_routes се чете и пише САМО от calendar.js (проверено с grep в целия
-- репозиторий, включително supabase/functions/). Друг потребител на
-- route_date няма, тоест изместването не разминава нищо друго.
-- route_templates НЕ се пипа: там няма дати, само day_of_week.
--
-- ПРЕДИ ПРИЛАГАНЕ
--   · created_at IS NULL — 0 реда към 13.09.2026. Ако се появи ред с NULL,
--     условието долу НЯМА да го измести; провери отново точно преди update.
--   · Уникален индекс има само по id — изместването не може да се сблъска
--     само със себе си по средата на update.
--   · <ЧАС_НА_МИГРАЦИЯТА> = моментът на прилагане (timestamptz). Редовете,
--     създадени СЛЕД него, идват от новия calendar.js и вече са верни.
--     Ред, създаден между миграцията и push-а, ще е записан от стария код и
--     ще остане с ден назад — затова push-ът е веднага след миграцията.

-- ─── проверка ПРЕДИ (очаквано: 0 → 25, 5 → 0, 6 → 0) ─────────────────────
-- select extract(dow from route_date) as dow, count(*) from bus_routes group by 1 order by 1;

-- ─── backup ──────────────────────────────────────────────────────────────
create table if not exists bus_routes_backup_20260913 as select * from bus_routes;

-- ОТКЛОНЕНИЕ ОТ ШАБЛОНА: RLS веднага след create table.
-- Правата по подразбиране в схема public дават на anon и authenticated
-- arwdDxtm върху ВСЯКА нова таблица (pg_default_acl, проверено 13.09.2026), а
-- create table … as select я създава БЕЗ RLS. Без този ред копието на всички
-- маршрути щеше да се чете и ПИШЕ с публичния anon ключ през PostgREST.
-- RLS без политика отрязва anon/authenticated; postgres и service_role (SQL
-- Editor, rollback-ът долу) не се засягат.
alter table bus_routes_backup_20260913 enable row level security;

-- ─── shift ───────────────────────────────────────────────────────────────
update bus_routes set route_date = route_date + 1
  where created_at < '2026-09-13 09:52:19+00';   -- приложено в този момент

